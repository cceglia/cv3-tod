//! Compiles the C shim against the distribution's libfprint TOD headers and links it into the
//! plugin.
//!
//! The shim needs `libfprint-2-tod-1` both for its headers and, at link time, for its versioned
//! symbols: glibc resolves an unversioned undefined reference to the *base* version of a symbol,
//! and `fpi_ssm_new_full` has a legacy 4-argument definition at `LIBFPRINT_TOD_1.0.0` and the
//! modern one at `LIBFPRINT_TOD_1_1.92`. `scripts/check-tod-link.sh` inspects the built object and
//! fails on the legacy binding; this script only has to make sure the library really is linked.
//!
//! The C object is linked by path rather than as a `cc` archive: rustc gives a `cdylib` a linker
//! version script that exports only the symbols the Rust crate declares, so symbols pulled in from
//! a static archive are local. The object's GType entry point is called from `src/ffi.rs`.
//!
//! The driver's identity (id, full name and device name) is defined here, once: it is written to a
//! header the shim includes and passed to `src/identity.rs` with `cargo:rustc-env`, so the C and
//! Rust sides cannot drift and neither repeats a literal the other holds.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The TOD package: headers, and the versioned symbols the shim must bind to.
const TOD_PACKAGE: &str = "libfprint-2-tod-1";
/// gusb, whose handle the shim releases when the open vfunc fails.
const GUSB_PACKAGE: &str = "gusb";
/// GLib's object system, which the shim calls directly through the generated type code.
const GLIB_PACKAGES: [&str; 2] = ["gobject-2.0", "glib-2.0"];

/// The driver id, reported by libfprint as the device's `driver`.
const CLASS_ID: &str = "cv3";
/// The human readable name of the driver's class.
const FULL_NAME: &str = "Dell/Broadcom ControlVault 3 fingerprint";
/// The name libfprint reports for the device after probe; `fprintd-list` prints this one.
const DEVICE_NAME: &str = "Dell/Broadcom ControlVault 3";

fn main() {
    println!("cargo:rerun-if-changed=shim/cv3_tod.c");
    println!("cargo:rerun-if-changed=build.rs");

    let manifest_dir = PathBuf::from(
        env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"),
    );
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));

    let packages = [
        TOD_PACKAGE,
        GUSB_PACKAGE,
        GLIB_PACKAGES[0],
        GLIB_PACKAGES[1],
    ];
    let cflags = pkg_config("--cflags", &packages);
    let libdir = pkg_config("--variable=libdir", &[TOD_PACKAGE]);
    let libs = pkg_config("--libs", &packages);

    write_identity_header(&out_dir);
    let object = compile_shim(&manifest_dir, &out_dir, &cflags);

    // The pkg-config libraries are reached through this directory when the distribution installs
    // them outside the linker's default search path.
    println!("cargo:rustc-link-search=native={libdir}");

    // The object goes on the linker command line before the libraries, so the references resolve
    // in source order. `--no-as-needed` guards that order against the distribution's default while
    // the object is present, and `--as-needed` restores the default afterwards so nothing rustc
    // appends later is force-kept.
    println!("cargo:rustc-link-arg-cdylib=-Wl,--no-as-needed");
    println!("cargo:rustc-link-arg-cdylib={}", object.display());
    for arg in split_flags(&libs) {
        println!("cargo:rustc-link-arg-cdylib={arg}");
    }
    println!("cargo:rustc-link-arg-cdylib=-Wl,--as-needed");
}

/// Writes the identity header the shim includes and publishes the same values to this crate.
///
/// `src/identity.rs` reads them with `env!`, so [`CLASS_ID`], [`FULL_NAME`] and [`DEVICE_NAME`]
/// exist once, here.
fn write_identity_header(out_dir: &Path) {
    let header = out_dir.join("cv3_tod_identity.h");
    let contents = format!(
        "/* Generated by build.rs: edit build.rs, not this file. */\n\
         #pragma once\n\
         #define CV3_TOD_CLASS_ID {}\n\
         #define CV3_TOD_FULL_NAME {}\n\
         #define CV3_TOD_DEVICE_NAME {}\n",
        c_string_literal(CLASS_ID),
        c_string_literal(FULL_NAME),
        c_string_literal(DEVICE_NAME)
    );
    fs::write(&header, contents)
        .unwrap_or_else(|error| panic!("could not write {}: {error}", header.display()));

    println!("cargo:rustc-env=CV3_TOD_CLASS_ID={CLASS_ID}");
    println!("cargo:rustc-env=CV3_TOD_FULL_NAME={FULL_NAME}");
    println!("cargo:rustc-env=CV3_TOD_DEVICE_NAME={DEVICE_NAME}");
}

/// Renders `value` as a C string literal, with the characters that would end or corrupt the literal
/// escaped, so a quote or a backslash in an identity value cannot break the generated header.
fn c_string_literal(value: &str) -> String {
    let mut literal = String::with_capacity(value.len() + 2);
    literal.push('"');
    for character in value.chars() {
        match character {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            '\n' => literal.push_str("\\n"),
            '\r' => literal.push_str("\\r"),
            '\t' => literal.push_str("\\t"),
            // Octal takes exactly three digits, so a following digit cannot extend it.
            other if other.is_control() => {
                literal.push_str(&format!("\\{:03o}", u32::from(other)));
            }
            other => literal.push(other),
        }
    }
    literal.push('"');
    literal
}

/// Compiles `shim/cv3_tod.c` with the builder's flags and returns the one object file.
fn compile_shim(manifest_dir: &Path, out_dir: &Path, cflags: &str) -> PathBuf {
    let source = manifest_dir.join("shim/cv3_tod.c");

    let mut build = cc::Build::new();
    build
        .file(&source)
        .include(out_dir)
        .out_dir(out_dir)
        // The object is loaded into fprintd, which runs as root, so it is hardened and optimised
        // (FORTIFY_SOURCE has no effect without optimisation).
        .opt_level(2)
        .warnings(true)
        .extra_warnings(true)
        .warnings_into_errors(true)
        .flag_if_supported("-std=gnu11")
        .flag("-fPIC")
        .flag_if_supported("-fstack-protector-strong")
        .flag_if_supported("-D_FORTIFY_SOURCE=2");
    for flag in split_flags(cflags) {
        build.flag(flag);
    }

    let mut objects = build.compile_intermediates();
    assert_eq!(objects.len(), 1, "the shim is a single source file");
    objects.pop().expect("the shim compiled to one object")
}

/// Runs `pkg-config` with `args` and returns its stdout, failing the build with an actionable
/// message when the TOD headers or library are missing.
fn pkg_config(args: &str, packages: &[&str]) -> String {
    let mut command = Command::new("pkg-config");
    command.arg(args).args(packages);

    let output = command.output().unwrap_or_else(|error| {
        panic!("could not run pkg-config ({error}); install pkg-config and libfprint-2-tod-dev")
    });
    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr);
        panic!(
            "pkg-config {args} {} failed: {}\n\
             the TOD plugin needs the distribution's libfprint TOD headers:\n\
             \x20   sudo apt install libfprint-2-tod-dev pkg-config",
            packages.join(" "),
            stderr.trim()
        );
    }
    String::from_utf8_lossy(&output.stdout).trim().to_string()
}

/// Splits a `pkg-config` flag string. The flags never contain spaces inside a value.
fn split_flags(flags: &str) -> impl Iterator<Item = &str> {
    flags.split_whitespace()
}
